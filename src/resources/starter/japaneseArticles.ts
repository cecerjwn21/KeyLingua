const article = (
  jlptLevel: NonNullable<PracticeDocument['jlptLevel']>,
  slug: string,
  title: string,
  lines: [string, string][],
  format: 'prose' | 'dialogue' = 'prose',
): PracticeDocument => ({
  id: `generated-keylingua-starter-ja-article-${jlptLevel.toLowerCase()}-${slug}`,
  title,
  source: 'generated',
  language: 'ja',
  jlptLevel,
  scenario: title,
  format,
  sentences: lines.map(([notation, translation]) => {
    const starterNotation = notation.replace(/[。？！]+$/u, '')
    return {
      name: starterNotation.replace(/\([^()]+\)/g, ''),
      notation: starterNotation,
      trans: [translation],
    }
  }),
})

