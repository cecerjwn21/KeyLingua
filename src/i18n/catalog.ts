const catalogs: Record<UiLocale, Catalog> = { 'zh-TW': zhTW, en, ja }

export type { UiTranslationKey }

export const translateUi = (locale: UiLocale, key: UiTranslationKey, parameters: Record<string, string | number> = {}) =>
  Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{{${name}}}`, String(value)),
    catalogs[locale][key] ?? zhTW[key],
  )
